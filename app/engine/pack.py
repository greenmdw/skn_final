"""
`DomainPack` — 도메인이 바뀔 때 갈아 끼우는 자리.

기획안 §3의 주장이 이 파일의 존재 이유다: *"이 엔진은 도메인이 바뀌어도 그대로다.
바뀌는 것은 세 칸뿐이다 — 품목 사전, 2단계의 외부 사실 소스, 리뷰 소스."*
`docs/목업/` 의 두 화면이 같은 6단계·같은 판정 체계로 그려진 것이 그 증거고,
여기서는 그 주장을 **코드가 지키게** 한다.

[세 칸이 아니라 네 칸이었다]
이음매를 실제로 그어 보니 기획안 §3 표가 세지 않은 것이 하나 있다 —
**3단계 ①의 하드 제약 룰**이다. 표는 3단계의 도메인 의존을 "리뷰 소스"로만
적었는데, PC 의 하드 제약은 소켓·전력이고 여행은 도보 시간·채식 가능 여부다.
같은 코드일 수가 없다. 그래서 `constraints()` 가 있다.

기획안을 고칠 일은 아니고(엔진이 도메인과 독립이라는 결론은 그대로다) 칸이 하나
더 있다는 사실만 여기 적어 둔다.

[도메인이 하나여도 이 프로토콜을 남기는 이유]
2026-09-08 기준 여행 도메인은 빠질 수 있다. 그래도 이 파일은 남긴다 — 멤버
다섯 개짜리 Protocol 이라 비용이 거의 없고, 3일에 네 번 흔들린 결정이 또
흔들릴 때 `packs/` 에 파일 하나 넣는 것으로 끝나기 때문이다. 플러그인 시스템도
설정 기반 로딩도 만들지 않는다 — 그건 실제로 둘째 팩이 생길 때 할 일이다.
"""

from __future__ import annotations

from typing import Protocol

from .schemas import Claim, NeedsInput, Requirement


class Part(Protocol):
    """품목 사전의 한 항목이 가져야 하는 것. 팩마다 필드를 더 가질 수 있다."""

    code: str
    category: str
    name: str
    price: int


class ReviewSourcePort(Protocol):
    """
    리뷰 소스. 실제 구현은 `app/reviews/` 에 있다.

    포트를 팩 바깥에 두는 이유: 도메인이 바뀌면 리뷰 **소스**가 바뀌지만
    (스토어 리뷰 ↔ 지역 리뷰), 3단계가 리뷰에게 묻는 것은 도메인과 무관하게
    *"이 주장에 어긋나는 언급이 표본 몇 건 중 몇 건인가"* 하나다.
    """

    name: str

    def evidence_for(self, claim: Claim): ...
    def risk_distribution(self) -> dict[str, int]: ...


class DomainPack(Protocol):
    """
    도메인 하나. 엔진은 이 프로토콜만 알고, 어떤 도메인인지는 모른다.

    구현체는 `packs/` 밑에 하나씩 둔다.
    """

    name: str

    # ── 칸 1: 품목 사전 ──────────────────────────────────────────────────
    def catalog(self) -> list[dict]:
        """거래 가능한 품목 전부. 카테고리·가격·사양을 포함한다."""
        ...

    def required_categories(self, known: dict) -> list[str]:
        """이번 요청에 필요한 카테고리. 재사용·비대상 품목을 여기서 뺀다."""
        ...

    def claims_for(self, code: str) -> list[Claim]:
        """그 품목에 대해 제조사/판매자가 하는 주장. 3단계의 입력이다."""
        ...

    def followups(self, known: dict) -> list[NeedsInput]:
        """
        1단계 되묻기. **룰베이스 빈칸 채우기다**(기획안 §3).

        `known` 에 이미 답이 있는 항목은 묻지 않는다. 이 함수가 빈 목록을
        돌려주면 엔진은 더 물을 게 없다고 보고 2단계로 간다.
        """
        ...

    # ── 칸 2: 외부 사실 ──────────────────────────────────────────────────
    def external_facts(self, known: dict) -> list[Requirement]:
        """
        2단계 — 모델의 상식이 아니라 **외부에서 오는 사실**.

        PC 는 게임사가 공개한 최소·권장 사양이다. 반드시 `as_of` 를 채울 것 —
        시차가 이 도메인의 알려진 약점이고, 기획안 §4의 대응이 *"시차 자체를
        화면에 쓴다"* 이다.
        """
        ...

    # ── 칸 3: 하드 제약 (기획안 §3 표가 세지 않은 칸) ────────────────────
    def constraints(self, candidate_set: list[dict]) -> list[str]:
        """
        3단계 ① — 조합이 성립하지 않는 이유를 돌려준다. 빈 목록이면 성립한다.

        **룰이고, 틀리면 물건이 안 돈다.** 그럴듯한 필터가 아니라 판정이다
        (기획안 §4: *"소켓이 안 맞으면 끝이다"*).
        """
        ...

    # ── 칸 4: 리뷰 소스 ──────────────────────────────────────────────────
    def review_source(self) -> ReviewSourcePort:
        """3단계 ③이 대조에 쓸 리뷰 소스."""
        ...
